import assert from 'node:assert/strict';
import vm from 'node:vm';
import worker from '../worker/index.js';

const defaultBackground = Uint8Array.from([82,73,70,70,0,0,0,0,87,69,66,80]);
const stored = new Map([['backgrounds/slot-1', defaultBackground]]);
const env = { BUCKET: { async get(key) { const bytes=stored.get(key); return bytes ? { body: bytes, httpMetadata:{contentType:'image/webp'} } : null; } } };
const req = path => new Request(`https://test.local${path}`);
const home = await worker.fetch(req('/'), env);
assert.equal(home.status, 200);
const html = await home.text();
assert.match(html, /Poster Preview|Poster · 1080/);
assert.match(html, /id="posterCanvas" width="1080" height="1350"/);
assert.match(html, /id="upcomingList"/);
assert.match(html, /id="openSettings"/);
assert.match(html, /id="downloadPoster"/);
assert.match(html, /id="settingTime"/);
assert.match(html, /id="settingLocation"/);
assert.match(html, /id="settingLocationDetail"/);
assert.match(html, /id="settingBackground"/);
assert.match(html, /id="saveDefaults"/);
assert.match(html, /Lịch Ảnh · Phóng Sinh Trong Suốt Huế/);
assert.match(html, /Be\+Vietnam\+Pro/);
assert.match(html, /Noto\+Serif/);
assert.doesNotMatch(html, /themePicker|theme marketplace|drag-and-drop|layer management|Đăng nhập|Quản lý background/);
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script);
assert.doesNotThrow(() => new vm.Script(script));
assert.match(script, /const POSTER_THEME=/);
assert.doesNotMatch(script, /POSTER_THEMES|function renderThemePicker|function refreshAuth/);
assert.match(script, /let savedDefaults=.*posterState=/);
assert.match(script, /localStorage\.setItem\(SETTINGS_STORAGE_KEY/);
assert.match(script, /document\.fonts\.load\('400 16px "Be Vietnam Pro"'/);
assert.match(script, /document\.fonts\.load\('700 80px "Noto Serif"'/);
assert.match(script, /await ensurePosterFonts\(\)/);
assert.match(script, /canvas\.toBlob/);
assert.match(script, /findEvents\(150\)\[0\]/);
assert.match(script, /weekday:'long'/);
assert.match(script, /Asia\/Ho_Chi_Minh/);
const themeStart=script.indexOf('const POSTER_THEME=');
const themeEnd=script.indexOf(';\nfunction timeOfDay',themeStart);
const design=vm.runInNewContext(`(()=>{${script.slice(themeStart,themeEnd+1)};return POSTER_THEME})()`);
assert.equal(design.name,'Zen Editorial');
assert.ok(design.type.gregorian.size>design.type.lunar.size,'Gregorian date is visually primary');
assert.equal(design.effects.strokeWidth,0);
assert.equal(design.effects.shadowBlur,0);
const dateFnStart=script.indexOf('function solarToLunar(');
const dateFnEnd=script.indexOf('\nfunction solarDate(',dateFnStart);
const lunarCode=script.slice(dateFnStart,dateFnEnd);
const jdCode=script.slice(script.indexOf('function jdFromDate('),dateFnStart);
const lunarContext=vm.runInNewContext(`(()=>{${jdCode}${lunarCode};return solarToLunar})()`);
assert.equal(JSON.stringify(lunarContext(22,3,2023)),JSON.stringify({day:1,month:2,year:2023,leap:1}));
assert.equal(JSON.stringify(lunarContext(23,11,2026)),JSON.stringify({day:15,month:10,year:2026,leap:0}));
const background=await worker.fetch(req('/api/background'),env);
assert.equal(background.status,200);
assert.equal(background.headers.get('content-type'),'image/webp');
assert.deepEqual(new Uint8Array(await background.arrayBuffer()),defaultBackground);
assert.equal((await worker.fetch(req('/api/images'),env)).status,404,'legacy image management is out of scope');
assert.equal((await worker.fetch(req('/api/admin/claim'),env)).status,404,'the simplified app has no account/admin flow');
console.log('Smoke checks passed: single poster flow, Gregorian-first hierarchy, local defaults, font loading, lunar leap month, original PNG export path, and the existing lotus background asset.');
